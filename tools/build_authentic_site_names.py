def generate_true_catalog():
    results = []
    
    for item in de_meta:
        sid = item['id']
        c = item['campaign']
        lvl = item['level']
        
        # Check direct or coop
        if sid in CATALOG:
            name, tp, hist, atk, dfn = CATALOG[sid]
        elif sid in COOP_SOURCE:
            src_id = COOP_SOURCE[sid]
            name, tp, hist, atk, dfn = CATALOG[src_id]
        else:
            old_item = orig.get(sid, {})
            name = old_item.get('name', '未定')
            tp = old_item.get('type', '中城')
            hist = old_item.get('history', '')
            atk = old_item.get('attacker', '')
            dfn = old_item.get('defender', '')
            
        old_item = orig.get(sid, {})
        size = old_item.get('size', 144)
        
        results.append({
            'id': sid,
            'scenario': item['scenario_file'].replace('.aoe2scenario', ''),
            'name': name,
            'type': tp,
            'basis': 'DE官方剧情+史实',
            'history': hist,
            'size': size,
            'attacker': atk,
            'defender': dfn
        })
        
    print(f"Generated {len(results)} true site name entries.")
    
    # Check types
    types = set(x['type'] for x in results)
    print("Distinct types used:", types)
    assert types.issubset({'大城', '中城', '小城', '城寨', '关隘', '战场'}), f"Unknown type: {types}"
    
    out_path = Path("public/de-maps/campaign/site_names.json")
    out_path.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"Successfully saved to {out_path}!")

if __name__ == '__main__':
    generate_true_catalog()
