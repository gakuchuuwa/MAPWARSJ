/**
 * 战略地图（zoom 8/9/10，非 13）军团方阵的**全部**尺寸与间距参数。
 *
 * 🔴 [2026-09-03 主人定：士兵比例统一、不搞特殊、看着真实] 只有一条规则：
 *
 *      单兵绘制尺寸 = DE 帧框 × (SPRITE_BASE_H × scale / DE_REF_FRAME_H)
 *      格位间距     = STRATEGIC_SPACING_X / _Y × scale（与兵种无关的常数）
 *
 * 兵模大小按 DE 原比例（象比步兵大 2.96 倍，与 DE 帧高比一致），**但站位间距与兵种无关**。
 *
 * ⚠️ 已删除、禁止写回：
 *   · 按行/按兵种算间距的 `rowMetrics`（2026-09-01 加的）。它让每排间距随该排兵种的帧框变化，
 *     于是孔雀（象+步+弓）的鱼鳞阵和纯步兵的鱼鳞阵形状不一样 —— 主人两次指出的正是这件事。
 *     实测 998 个编成里 441 个「前→中」与「中→后」行距不等，最大差 4.42 倍。
 *   · 与素材无关的常数间距下限（「只抬不降」）。
 *   · `kongque` 势力专属行距系数 0.58/0.75。
 *
 * ⚠️ 只管战略地图。zoom 13 走 LegionPhalanxDrawer.computeDenseSpacing，是另一套，别混。
 *
 * 验收：`npm run legion:spacing-audit`（全势力编成扫一遍，「间距÷绘制尺寸」必须全局唯一）
 */

/** DE / S10DB 素材的参考帧高，换算绘制缩放用。素材换代前不要动。 */
export const DE_REF_FRAME_H = 64;

/**
 * 战略地图单兵绘制基准高。**整体调大调小只动这一个数。**
 * 调整史：75/60（初版）→ 68/54（2026-08-20 主人「战略地图的兵有点大」）
 *       → 73/58（2026-09-01 主人「军团稍大一点」）
 *       → 68（2026-09-03 主人「士兵素材有点小，统一大一点」，+17%；
 *             此时间距已改为由绘制尺寸推导，不再需要同步调第二个数）
 */
export const SPRITE_BASE_H = 68;

/**
 * 方阵格位间距（横 / 纵），单位是「屏幕像素 ÷ scale」。实际间距 = 这个数 × scale。
 *
 * 🔴 [2026-09-03 主人定：不看兵种，七个阵型的间距一样] 这是**一对常数**，不读任何素材尺寸。
 *    阵型形状只由 *_9_LAYOUT 的 (r, c) 决定，所以同一个阵型在任何势力、任何兵种下长得一模一样。
 *    **兵种是会来回换的，间距不能跟着兵种走** —— 否则同一个「鱼鳞阵」换了兵就变形。
 *
 *    数值按 zoom9（scale=0.7）出图挑的：横 32px / 纵 44px。象、纯步兵、骑步弓三种典型军团
 *    在这一档都读得出前中后三排 —— 象不糊成一坨，步兵不散架，前排也不会串到中排里。
 */
export const STRATEGIC_SPACING_X = 46;
export const STRATEGIC_SPACING_Y = 63;
