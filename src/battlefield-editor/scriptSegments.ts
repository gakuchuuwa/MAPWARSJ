export interface ScriptSegment {
    /** 段号：`片-段`，如 `2-3` */
    id: string;
    /** 片号与片名 */
    part: number;
    partName: string;
    /** 段的起点 → 终点（中间节点按史料途经地列出） */
    from: string;
    to: string;
    /** 途经节点（线内的点，不上图、不判定） */
    via: string[];
    /** 这一段覆盖的场次号（1 起，按年份季节排序） */
    events: number[];
    /** 这一段里有没有仗（false ＝ 纯行军段） */
    hasBattle: boolean;
    /** 纯行军段的旁白由哪一场的赶路播报覆盖（有仗的段写本段所含的场） */
    briefedBy: number[];
    /** 同一条线在数据里的读法（供编辑核对） */
    note?: string;
}

