/** 番号字数（按字符数算，不用 UTF-16 长度，免得生僻字/表情算错） */
export function eliteNameCharCount(name: string): number {
    return [...String(name ?? '').trim()].length;
}

/** 番号合规检查：合规返回 null，不合规返回一句人能看懂的理由 */
export function eliteNameViolation(name: string): string | null {
    const raw = String(name ?? '').trim();
    if (!raw) return '番号为空';
    if (ELITE_HISTORIC_NAMES.has(raw)) return null;   // 有史源：字数不限
    const n = eliteNameCharCount(raw);
    if (n < ELITE_NAME_MIN) return `番号「${raw}」只有 ${n} 字：自拟番号要 ${ELITE_NAME_MIN}–${ELITE_NAME_MAX} 字（按史原名请登记进 ELITE_HISTORIC_NAMES）`;
    if (n > ELITE_NAME_MAX) return `番号「${raw}」有 ${n} 字：自拟番号要 ${ELITE_NAME_MIN}–${ELITE_NAME_MAX} 字（按史原名请登记进 ELITE_HISTORIC_NAMES）`;
    return null;
}
