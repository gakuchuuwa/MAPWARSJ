/** 知名战三分类（主人 2026-11-09 定）：野战 / 攻城 / 防守 */
export type FirstBattleKind = 'field' | 'siege_attack' | 'siege_defend';

/** 由首战条目的 battleType ＋ role 唯一判定三分类 */
export function firstBattleKindOf(fb: Pick<GeneralFirstBattle, 'battleType' | 'role'>): FirstBattleKind {
    if (fb.battleType !== 'siege') return 'field';
    return (fb.role ?? 'attacker') === 'defender' ? 'siege_defend' : 'siege_attack';
}

