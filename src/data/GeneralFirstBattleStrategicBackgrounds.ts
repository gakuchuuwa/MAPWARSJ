const CN_DIGITS = ['〇', '一', '二', '三', '四', '五', '六', '七', '八', '九'];

/** 年份 → 播报口径（公元前六三二年、公元一七〇九年），与开战背景文案同一写法 */
function spokenYear(year: number): string {
    const digits = String(Math.abs(year)).split('').map((d) => CN_DIGITS[Number(d)]).join('');
    return year < 0 ? `公元前${digits}年` : `公元${digits}年`;
}

/** 没写专条的场次：按经典战数据拼一句大局（年份、双方、统帅、去向），保证赶路时不冷场 */
function fallbackStrategicLine(fb: GeneralFirstBattle, myFactionName: string, generalName: string, enemyFactionName: string): string {
    const kind = fb.battleType !== 'siege' ? '大战' : ((fb.role ?? 'attacker') === 'defender' ? '守城之战' : '攻城之战');
    const sides = myFactionName && myFactionName !== enemyFactionName
        ? `${myFactionName}与${enemyFactionName}兵戈相向`
        : `${enemyFactionName}兴兵而来`;
    return `${spokenYear(fb.battleYear)}，${sides}。${generalName}奉命统军，奔赴${fb.targetName}，一场关乎双方兴衰的${kind}即将打响。`;
}

/**
 * 战略大局要念的各段（一段一屏）。优先级：云盘回填表导入的 → 本表手写专条 → 按数据拼一句。
 */
export function getFirstBattleStrategicParagraphs(
    fb: GeneralFirstBattle,
    names: { myFactionName: string; generalName: string; enemyFactionName: string },
): string[] {
    const id = fb.battleId ?? fb.generalId;   // 🔴 一名将多场：按这一场的编号取（第一场＝generalId）
    // 🔴 [2026-11-13] 编年史之战：文案只认编年史 json（唯一真源）
    const chron = getChronicleBriefing(id)?.strategic.filter((p) => p.trim());
    if (chron?.length) return chron;
    const imported = CLASSIC_BATTLE_BRIEFINGS[id]?.strategic?.filter((p) => p.trim());
    if (imported?.length) return imported;
    const hand = FIRST_BATTLE_STRATEGIC_BACKGROUNDS[id];
    if (hand) return [hand];
    return [fallbackStrategicLine(fb, names.myFactionName, names.generalName, names.enemyFactionName)];
}
