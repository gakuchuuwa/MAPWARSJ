/**
 * 剧本期据点**显示名**（剧本那一年的叫法）—— 🔴 [2026-09-25 主人令]
 *
 * 主人原话：「据点的名字，文案要和图上的统一。」「不要用亚历山大城这种名字，太俗气了，而且知名度不高。」
 * 「我们是后人解读亚历山大的历史，我认为可以用后世知名度大的地名。」
 *
 * 取名原则（两条合起来看）：
 *   ① **图上与文案必须是同一个名字** —— 文案念「菲利波波利斯」，图上却标「普罗夫迪夫」，
 *      玩家读到的地名在图上看不见 ✗；
 *   ② **取现代读者认得出的那一个**（后世知名度大的地名优先）：
 *      · 库里本来就是后世通用名的（喀布尔、撒马尔罕、坎大哈、大马士革…）→ **不动**，
 *        文案反过来跟图上走（段表与播报都用库里的名字）；
 *      · 只有**中国人读亚历山大史那个传统里已经通用**的古名，才在剧本期覆盖显示名
 *        （拜占庭、菲利波波利斯、埃克巴坦那 —— 中译《亚历山大远征记》一路用的就是这三个）；
 *      · **绝不生造**「阿利亚的亚历山大城」「阿拉霍西亚的亚历山大城」这类又长又生僻的构造名。
 *
 * 只列**要换名字**的城；剧本期由 `src/events/scriptCityNamesSync.ts` 套上 / 撤下：
 *   · 进剧本期：`name` 换成剧本期叫法 + 刷新地图标签；
 *   · 切回乱斗：换回原名的城还原（已被玩家改名/易主流程动过的不碰）。
 *
 * 守则：
 *   ① 只改**显示名**，`id` 一律不动（寻路、归属、战斗、存档一概按 id，不受影响）；
 *   ② 每个名字必须有史料出处（维基为基准 + 当地语种为辅），查不到的不列；
 *   ③ 这是「同一个地方换个时代的叫法」，**不是新建据点**。
 */
