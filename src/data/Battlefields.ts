export interface BattlefieldData {
    /** 🔴 战场 id（**不是** `city_*`，不进据点表）：`bf_` + 拼音 */
    id: string;
    /** 战场地名（一个地名而已） */
    name: string;
    /** 真实坐标。🔴 **必须与该场剧本 `fieldBattleData.location` 一字不差** */
    lat: number;
    lng: number;
    /** 哪一年的剧本打完它才上图（对应 `HistoricalEventScript` 的 `year`） */
    scriptYear: number;
    note?: string;
    /**
     * 🔴 [2026-09-16 主人定] 赶路背景播报 —— 玩家**在奔赴这个战场的路上**逐段播的背景介绍。
     * 与「事件播报」「战役播报」都不是一回事：那两条是战役本身的说明，这条是路上的铺垫。
     * 空行分段，每段一条 toast 依次推送（见 `PlayerQuestSystem.startJourneyBriefing`）。
     */
    briefing?: string;
    /**
     * 🔴 [2026-09-19 主人定] **在场人物** —— 「缺少的人物，做成战场人物。人物和战场点绑定。」
     *
     * 存的是 `BattlefieldCharacters.ts` 里那些**只在场战上出现**的人物 id
     * （窦建德 / 王世充 / 保卢斯 / 瓦罗 / 埃提乌斯…）。他们不属于任何据点，只属于这一块战场；
     * 玩家在选边对话框里看到的那两位主帅，就是这里的人。
     *
     * ⚠️ 与 `HistoricalEventScript` 的 `generalId`（**这一仗是谁的**）不是一回事：
     *    那个回答「玩家找谁接这一仗」，这个回答「这一仗现场有谁」。
     */
    roster?: string[];
    /**
     * 🔴 [2026-09-19 主人定] **这个战场打的是哪座城**（只有攻城战要用）。
     *
     * 主人原话：「战场和现有据点不是一回事，所有战场都新建。」
     *   → 战场标牌标在**史实地点**（一之谷 34.64,135.10，今神户须磨区），
     *     而攻城战打的是那座**据点**（最近的姬路城 34.8394,134.6939，相距 43km）。
     *   两者本来就不是一个坐标，所以**不能拿坐标去配对**：第一批实测一之谷的经纬差是
     *   0.1994 / 0.4061，任何"合理的"度容差都盖不住这 43km，放宽到 0.5 度又会串到别的城。
     *
     * 故攻城战改成**显式指名**：本字段写被攻据点 id。运行时据此
     *   ① `findHistoricalEventOfGeneral` 把战场配回战役（不再比坐标）；
     *   ② 玩家的军团赶路终点（见 `PlayerQuestSystem.joinGeneralEvent`）。
     * 野战不用本字段（野战的契约仍是「战场坐标 === 条目 location」）。
     */
    eventCityId?: string;
    /**
     * 🔴 [2026-09-19 主人定「建立一个一之谷战场」] **这块战场本身就是攻城目标**（战场要塞）。
     *
     * 一之谷这种要塞：它**不是据点**（不进 `cities_v2`、不算任何势力的城），
     * 但史实上它就是被强攻拿下的。故攻城战写成「打这块战场」——
     * `SiegeData.targetBattlefieldId` 填本战场的 id，引擎据此用战场记录合成攻城目标。
     *
     * 与 `eventCityId` **二选一**：
     *   · 打**据点**（推罗战役）→ `eventCityId`（值 = `city_*`）
     *   · 打**战场要塞**（一之谷战役）→ 本字段（值 = `bf_*`）
     */
    eventBattlefieldId?: string;
    /**
     * 🔴 [2026-09-19 主人定] **战场攻城战的标注套用据点样式**。
     *
     * 主人原话：「这种战场攻城战，标注上，套用大中小城寨哪个据点的样式就行。」
     *   → 战场平时画「战场形态」（拒马/尸体/骨骸/火把…）；但**攻城战**是打一座**砦/城**，
     *     它该长成据点那样 —— 本字段写用哪一档：
     *     `big_city` 大城 ／ `medium_city` 中城 ／ `small_city` 小城 ／ `stockade` 城寨 ／ `pass` 险要。
     *
     * 留空 = 仍画普通战场形态（**野战一律留空**）。
     * 样式本身由 `TerritorySystem.buildSiegeCastleStackHtml()` 用**据点同一套组装**画出来
     * （风格判据、石/木墙、中心城堡全部与据点一致，没有第二套画法）。
     */
    siegeCastleType?: CityType;
}

