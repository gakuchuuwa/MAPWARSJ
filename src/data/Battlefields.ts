/**
 * 🔴 [2026-09-25 主人「有的战场离据点太近了，根本无法连接，怎么办。能不能归为一个点」]
 * 离某座据点不超过这个距离（公里）的战场，在**路网里归为那座据点**：不另立节点、不用画支线，
 * 道路连到这个战场就等于连到那座城。战场自己的坐标、标牌、剧本位置一概不变，只是「走路」共用那座城。
 * 实测（2026-09-25）：格拉尼库斯河距格拉尼库斯 0.4 km、锡尔河距忽毡 5.3 km → 归并；
 * 其余最近的海达斯佩斯河距蒙格 23 km，照常画支线。
 */
export const BATTLEFIELD_MERGE_KM = 10;

const mergedCityCache = new Map<string, string | null>();
/** 这个战场在路网里归到哪座据点（null = 不归并，是独立的路网端点） */
export function battlefieldMergedCityId(bfId: string): string | null {
    if (mergedCityCache.has(bfId)) return mergedCityCache.get(bfId)!;
    const bf = getBattlefield(bfId);
    let best: string | null = null;
    if (bf) {
        const r = Math.PI / 180;
        let bestKm = BATTLEFIELD_MERGE_KM;
        for (const c of CITIES_V2) {
            const h = Math.sin((c.lat - bf.lat) * r / 2) ** 2
                + Math.cos(bf.lat * r) * Math.cos(c.lat * r) * Math.sin((c.lng - bf.lng) * r / 2) ** 2;
            const km = 12742 * Math.asin(Math.sqrt(h));
            if (km <= bestKm) { bestKm = km; best = c.id; }
        }
    }
    mergedCityCache.set(bfId, best);
    return best;
}

/**
 * 🔴 [2026-09-19 主人定] 某位武将的史实战役 → 它对应的战场（战役**打在哪**）。
 *
 * 主人原话：「每个武将一个真实的历史事件」。战役条目上新增的 `generalId` 就是「这一仗是谁的」，
 * 本函数把它翻成战场记录（`bf_*`，含坐标与地名），玩家要赶路去的就是这个坐标。
 *
 * ⚠️ 与 `matchesBattlefield`（把战场配回战役）方向相反：那个是**战场 → 战役**（跑步时反查），
 *    这个是**武将 → 战场**（玩家接活时正查），两个函数都必须走同一条数据契约，
 *    即「战役与战场同年 + 坐标接近」，故此处复用 `matchesBattlefield`，不另写一套判据。
 *
 * @returns 找不到配对的战场时返回 null（＝这条事件还没在 `Battlefields.ts` 里落战场，玩家接不了）
 */
export function findBattlefieldOfGeneralEvent(
    eventYear: number,
    loc: { lat: number; lng: number } | null | undefined,
): BattlefieldData | null {
    if (!loc) return null;
    return BATTLEFIELDS.find((b) => matchesBattlefield(b, eventYear, loc)) ?? null;
}

/**
 * 这条战役事件**打在哪**（战场坐标）。
 *
 * 🔴 [2026-09-19] 与运行时 `findBattleForBattlefield`、编辑器 `loadDrafts` **同一套口径**：
 *    · 野战 / 有 `location` 的条目 → 直接用 `location`
 *    · 攻城战没有 `location`（推罗就是靠 `defenderCityId` + 航点走的）→ 取**被攻据点**的坐标
 *   三处只要有一处口径不同，就会出现「编辑器配得上、玩家却到不了」的暗坑。
 */
export function battlefieldLocationOf(
    data: { location?: { lat: number; lng: number } | null; defenderCityId?: string } | null | undefined,
    cityLookup: (id: string) => { lat: number; lng: number } | undefined,
): { lat: number; lng: number } | null {
    if (!data) return null;
    if (data.location) return data.location;
    if (data.defenderCityId) {
        const c = cityLookup(data.defenderCityId);
        if (c) return { lat: c.lat, lng: c.lng };
    }
    return null;
}

/* ── 【战场 ↔ 剧本条目 的唯一配对判据】2026-09-17 ─────────────────────────────────
 * 修的是**两处判据不一致**：改之前运行时（HistoricalEventManager.findBattleForBattlefield）
 * 按「距离 ≤ 0.15 度」配、**完全不看年份**，取数组里第一个命中的；编辑器（battlefield-editor）
 * 按「同年 + 0.5 度」配。两条隐患：
 *   ① 运行时不看年份 → 同一地点将来有第二场战役（同地二战很常见），必定配错年份的那场；
 *   ② 容差差了三倍多（0.15≈16km / 0.5≈55km）→ 坐标写歪 0.3 度时，编辑器显示配对成功、
 *      运行时却找不到，表现为「点了战场没反应」，而编辑器一切正常，极难查。
 *
 * 实测（scratch/_probe_bf_match.mjs，14 条战役 × 14 个战场）：现有数据坐标**全部一字不差**
 *   （距离全是 0）、年份全对、两种容差下都唯一命中 —— 没有实际故障，所以收紧判据零风险。
 *
 * 判据取 BattlefieldData.lat/lng 头注那句已有的数据契约：「必须与该场剧本 location 一字不差」。
 * 容差留 0.15 度不是为了容错，是给攻城战用的 —— 攻城战条目没有 location，坐标取被攻据点的，
 * 与战场标记点本来就会差一点。真要一字不差就把它调成 0。
 */
export const BATTLEFIELD_MATCH_DEG = 0.15;

/** 这个战场是不是那条剧本条目打的。两处（运行时 / 编辑器）必须都走它，别再各写一套。 */
/**
 * 🔴 [2026-09-24 主人定「所有事件就两种：野战，战后显示战场；攻城战，攻城战必须有据点……攻城战，你搞什么战场呀」]
 * 攻城战没有战场记录。它在剧本流程里的编号（记「打没打过」、排先后）由「被攻据点 + 年份」生成，不画任何战场标牌。
 */
export function siegeSiteId(cityId: string, year: number): string {
    return `siege_${cityId}_${year}`;
}
export function isSiegeSiteId(id: string): boolean {
    return id.startsWith('siege_');
}

export function matchesBattlefield(
    bf: BattlefieldData,
    eventYear: number,
    loc: { lat: number; lng: number } | null | undefined,
): boolean {
    if (!loc) return false;
    if (bf.scriptYear !== eventYear) return false;
    return Math.abs(bf.lat - loc.lat) <= BATTLEFIELD_MATCH_DEG
        && Math.abs(bf.lng - loc.lng) <= BATTLEFIELD_MATCH_DEG;
}
